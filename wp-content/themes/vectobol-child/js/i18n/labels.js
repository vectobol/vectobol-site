/* =========================
   LANGUAGE DETECTION
========================= */
function getLang() {
  return (document.documentElement.lang || "fr")
    .toLowerCase()
    .split("-")[0];
}

/* =========================
   TRANSLATION FUNCTION
========================= */
function t(key) {
  const lang = (document.documentElement.lang || "fr")
    .toLowerCase()
    .split("-")[0];

  return window.VECTOBOL_I18N?.labels?.[lang]?.[key]
      ?? window.VECTOBOL_I18N?.labels?.fr?.[key]
      ?? key;
}

function applyI18N() {

  const lang = getLang();

  const dict =
    window.VECTOBOL_I18N?.labels?.[lang]
    || window.VECTOBOL_I18N?.labels?.fr;

  if (!dict) return;

  /* Texte des éléments */
  document.querySelectorAll("[data-i18n]").forEach(el => {

    const key = el.dataset.i18n;

    if (dict[key]) {
      el.textContent = dict[key];
    }

  });

  /* Placeholder des champs */
  document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {

    const key = el.dataset.i18nPlaceholder;

    if (dict[key]) {
      el.placeholder = dict[key];
    }

  });

}

/* =========================
   GLOBAL EXPORT (NON-MODULE)
========================= */
window.VECTOBOL_I18N = {
  labels,
   getLang,
  t,
  applyI18N
  
};

document.addEventListener("DOMContentLoaded", () => {
  window.VECTOBOL_I18N?.applyI18N?.();
});
